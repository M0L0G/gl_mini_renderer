#!/usr/bin/env python3
"""Generate the small offline assets used by gl_mini_renderer.

Only the Python standard library is required. This keeps the repository free
of downloaded assets and lets anyone regenerate them deterministically:

    python tools/generate_assets.py
"""
from __future__ import annotations

import math
import os
import struct
import zlib


ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def write_png(path: str, width: int, height: int, pixels: bytearray) -> None:
    """Write an RGBA8 PNG without external dependencies."""
    raw = bytearray()
    for y in range(height):
        raw.append(0)  # filter type: none
        row = y * width * 4
        raw.extend(pixels[row:row + width * 4])

    def chunk(tag: bytes, payload: bytes) -> bytes:
        return (struct.pack(">I", len(payload)) + tag + payload
                + struct.pack(">I", zlib.crc32(tag + payload) & 0xFFFFFFFF))

    header = struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0)
    png = bytearray(b"\x89PNG\r\n\x1a\n")
    png.extend(chunk(b"IHDR", header))
    png.extend(chunk(b"IDAT", zlib.compress(bytes(raw), 9)))
    png.extend(chunk(b"IEND", b""))
    with open(path, "wb") as handle:
        handle.write(png)


def generate_checker() -> None:
    size = 512
    cells = 8
    color_a = (184, 186, 179)
    color_b = (71, 82, 89)
    cell = size / cells
    state = 0x5EED1234
    pixels = bytearray(size * size * 4)

    for y in range(size):
        for x in range(size):
            state ^= (state << 13) & 0xFFFFFFFF
            state ^= state >> 17
            state ^= (state << 5) & 0xFFFFFFFF
            noise = ((state & 0xFFFFFF) / 16777216.0 - 0.5) * 0.055

            cx = min(int(x / cell), cells - 1)
            cy = min(int(y / cell), cells - 1)
            base = color_a if ((cx + cy) & 1) == 0 else color_b
            local_x = x - math.floor(x / cell) * cell
            local_y = y - math.floor(y / cell) * cell
            if (local_x < 2 or local_y < 2 or local_x >= cell - 2
                    or local_y >= cell - 2):
                factor = 0.72
            else:
                factor = 1.0

            index = (y * size + x) * 4
            pixels[index + 0] = max(0, min(255, round(base[0] * factor + noise * 255)))
            pixels[index + 1] = max(0, min(255, round(base[1] * factor + noise * 255)))
            pixels[index + 2] = max(0, min(255, round(base[2] * factor + noise * 255)))
            pixels[index + 3] = 255

    path = os.path.join(ROOT, "assets", "textures", "checker.png")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    write_png(path, size, size, pixels)
    print(f"wrote {path}")


def generate_torus() -> None:
    major_radius = 1.7
    tube_radius = 0.5
    major_segments = 64
    minor_segments = 32
    two_pi = math.pi * 2.0

    lines = [
        "# Procedurally generated by tools/generate_assets.py",
        "# A torus with explicit positions, normals and UVs for tinyobjloader.",
        "o torus",
    ]

    for i in range(major_segments + 1):
        u = i / major_segments
        a = u * two_pi
        center = (math.cos(a) * major_radius, 0.0, math.sin(a) * major_radius)
        outward = (math.cos(a), 0.0, math.sin(a))
        for j in range(minor_segments + 1):
            v = j / minor_segments
            b = v * two_pi
            nx = outward[0] * math.cos(b)
            ny = math.sin(b)
            nz = outward[2] * math.cos(b)
            length = math.sqrt(nx * nx + ny * ny + nz * nz)
            nx, ny, nz = nx / length, ny / length, nz / length
            px = center[0] + nx * tube_radius
            py = center[1] + ny * tube_radius
            pz = center[2] + nz * tube_radius
            lines.append(f"v {px:.6f} {py:.6f} {pz:.6f}")
            lines.append(f"vt {u:.6f} {v:.6f}")
            lines.append(f"vn {nx:.6f} {ny:.6f} {nz:.6f}")

    def vid(i: int, j: int) -> int:
        return i * (minor_segments + 1) + j + 1

    for i in range(major_segments):
        for j in range(minor_segments):
            a = vid(i, j)
            b = vid(i + 1, j)
            c = vid(i + 1, j + 1)
            d = vid(i, j + 1)
            lines.append(f"f {a}/{a}/{a} {c}/{c}/{c} {b}/{b}/{b}")
            lines.append(f"f {a}/{a}/{a} {d}/{d}/{d} {c}/{c}/{c}")

    path = os.path.join(ROOT, "assets", "models", "torus.obj")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="ascii", newline="\n") as handle:
        handle.write("\n".join(lines))
        handle.write("\n")
    print(f"wrote {path}")


if __name__ == "__main__":
    generate_checker()
    generate_torus()
